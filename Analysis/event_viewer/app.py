@app.callback(
    Output("nvac-dd", "options"),
    Output("nvac-dd", "value"),
    Input("composition-dd", "value"),
)
def update_nvac(compositions):
    comps = _as_list(compositions)
    if not comps:
        return [], []
    nvacs: set[int] = set()
    for comp in comps:
        for n in CASCADE.get(comp, {}):
            nvacs.add(n)
    ordered = sorted(nvacs)
    return _to_options(ordered), [str(n) for n in ordered]


@app.callback(
    Output("temp-dd", "options"),
    Output("temp-dd", "value"),
    Input("nvac-dd", "value"),
    State("composition-dd", "value"),
)
def update_temp(nvacs, compositions):
    comps = _as_list(compositions)
    nvac_list = _as_list(nvacs)
    if not comps or not nvac_list:
        return [], []
    temps: set[int] = set()
    for comp in comps:
        for n_str in nvac_list:
            try:
                n = int(n_str)
            except (TypeError, ValueError):
                continue
            for t in CASCADE.get(comp, {}).get(n, []):
                temps.add(int(t))
    ordered = sorted(temps)
    return _to_options(ordered), [str(t) for t in ordered]


