@app.callback(
    Output("event-graph", "figure"),
    Output("status-bar", "children"),
    Input("selected-event", "data"),
    Input("frame-radio", "value"),
    Input("color-mode-radio", "value"),
    Input("vacancy-checkbox", "value"),
    Input("atom-size-slider", "value"),
    Input("render-style-radio", "value"),
    Input("direction-overlay-checklist", "value"),
    State("camera-store", "data"),
)
def render_graph(
    selected, frame, color_mode, vacancy_check, atom_size, render_style,
    direction_overlays, camera_store,
):
    if not selected:
        return empty_figure("Click a point on the scatter to load an event."), \
               _breadcrumb_empty("no event selected")
    sim = _resolve_sim(_sim_key(
        selected["composition"], selected["nvac"],
        float(selected["temp"]), selected["coloring"],
    ))
    if sim is None:
        return empty_figure("Could not resolve selected run."), \
               _breadcrumb_empty("could not resolve selected run")
    events = load_events(sim, CLASSIFICATIONS)
    if events.empty:
        return empty_figure("No events in this run."), \
               _breadcrumb_empty(f"no events in {sim.path}")
    match = events[events["idx_ref"] == int(selected["idx_ref"])]
    if match.empty:
        return empty_figure(f"Event #{selected['idx_ref']} not found."), \
               _breadcrumb_empty(f"event #{selected['idx_ref']} not found")

    show_vacancies = bool(vacancy_check) and "on" in (vacancy_check or [])
    try:
        size = float(atom_size) if atom_size is not None else 1.0
    except (TypeError, ValueError):
        size = 1.0
    overlays = set(direction_overlays or [])

    # Carry over the user's camera (rotate / pan / zoom) when they're
    # toggling within the same event. camera-store is stamped with
    # idx_ref by the clientside capture callback; only honour it when
    # the stored event matches the one we're rendering. If it doesn't,
    # fall back to the on-disk saved default for this event (set via
    # the Lock view button); if none, let Plotly auto-fit.
    #
    # Priority order:
    #   1. Live session camera (camera-store, idx_ref matches)
    #   2. Persisted default (view_defaults.json, keyed by event tuple)
    #   3. None → Plotly auto-fits to bounding box
    camera_state = None
    try:
        if (camera_store
                and camera_store.get("idx_ref") is not None
                and int(camera_store["idx_ref"]) == int(selected["idx_ref"])
                and camera_store.get("eye")):
            camera_state = {"eye": camera_store["eye"]}
            if camera_store.get("center") is not None:
                camera_state["center"] = camera_store["center"]
            if camera_store.get("up") is not None:
                camera_state["up"] = camera_store["up"]
    except (TypeError, ValueError):
        camera_state = None
    if camera_state is None:
        try:
            saved = _vd_get_default(
                composition=str(selected["composition"]),
                nvac=int(selected["nvac"]),
                temp=float(selected["temp"]),
                idx_ref=int(selected["idx_ref"]),
            )
            if saved and saved.get("eye"):
                camera_state = {"eye": saved["eye"]}
                if saved.get("center") is not None:
                    camera_state["center"] = saved["center"]
                if saved.get("up") is not None:
                    camera_state["up"] = saved["up"]
        except (TypeError, ValueError, KeyError):
            pass

    fig = make_event_figure(
        match.iloc[0],
        frame=frame,
        color_mode=color_mode or "element",
        show_vacancies=show_vacancies,
        atom_size=size,
        render_style=render_style or "markers",
        overlay_110_inplane="<110>_inplane" in overlays,
        overlay_100_inplane="<100>_inplane" in overlays,
        overlay_111_interlayer="<111>_interlayer" in overlays,
        overlay_001_exchange="<001>_exchange" in overlays,
        camera_state=camera_state,
    )
    row = match.iloc[0]
    crumbs = _build_breadcrumbs(
        composition=str(selected["composition"]),
        nvac=int(selected["nvac"]),
        temp=float(selected["temp"]),
        idx=int(selected["idx_ref"]),
        energy_barrier=float(row["energy_barrier"]),
        move_type=row.get("move_type", "?"),
        family_id=row.get("family_id", ""),
        total=len(SCATTER_DF),
    )
    return fig, crumbs


