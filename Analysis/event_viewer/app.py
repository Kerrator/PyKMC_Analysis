def persist_view_default(trig: dict[str, Any] | None):
    """Write the locked camera to view_defaults.json keyed by event tuple."""
    if not trig:
        raise PreventUpdate
    event = trig.get("event") or {}
    eye = trig.get("eye")
    if not eye or event.get("idx_ref") is None:
        raise PreventUpdate
    try:
        _vd_save_default(
            composition=str(event["composition"]),
            nvac=int(event["nvac"]),
            temp=float(event["temp"]),
            idx_ref=int(event["idx_ref"]),
            eye=eye,
            center=trig.get("center"),
            up=trig.get("up"),
        )
    except Exception as exc:
        return "⚠ save failed", f"view_defaults save failed: {exc}"
    idx = int(event["idx_ref"])
    return "🔒 locked", f"Default view saved for event #{idx}"


