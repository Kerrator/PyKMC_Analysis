def _to_options(values: list) -> list[dict]:
    return [{"label": str(v), "value": str(v)} for v in values]


def _as_list(values: Any) -> list[str]:
    """Normalize a multi-select dropdown value to a list of strings."""
    if values is None:
        return []
    if isinstance(values, (list, tuple)):
        return [str(v) for v in values]
    return [str(values)]


def _sim_key(composition: str, nvac: int, temperature: float, coloring: str) -> str:
    return json.dumps([composition, int(nvac), float(temperature), coloring])


def _resolve_sim(key: str):
    try:
        composition, nvac, temp, coloring = json.loads(key)
    except (TypeError, ValueError, json.JSONDecodeError):
        return None
    for sim in RESOLVER.get((composition, int(nvac), float(temp)), []):
        if sim.coloring == coloring:
            return sim
    return None


def _pick_full_coloring(sims_for_triple: list) -> str | None:
    if not sims_for_triple:
        return None
    for s in sims_for_triple:
        if s.coloring == "full":
            return s.coloring
    for s in sims_for_triple:
        if "full" in s.coloring:
            return s.coloring
    return sims_for_triple[0].coloring


def _selected_event_dict(composition: str, nvac: int, temp: float,
                         idx_ref: int) -> dict | None:
    """Package a selected event into the sim triple + coloring + idx_ref store."""
    sims_for_triple = RESOLVER.get((composition, int(nvac), float(temp)), [])
    coloring = _pick_full_coloring(sims_for_triple)
    if coloring is None:
        return None
    return {
        "composition": composition,
        "nvac": int(nvac),
        "temp": float(temp),
        "coloring": coloring,
        "idx_ref": int(idx_ref),
    }


def _initial_selected_event() -> dict | None:
    """Pick the first classified event as the default so the 3D view starts populated."""
    if SCATTER_DF.empty:
        return None
    row = SCATTER_DF.iloc[0]
    return _selected_event_dict(
        str(row["composition"]), int(row["nvac"]), float(row["temp"]),
        int(row["idx_ref"]),
    )


def _crumb(label: str, value: str, gold: bool = False) -> "html.Span":
    """Single crumb: uppercase label + value. Gold variant for accents."""
    return html.Span(
        [
            html.Span(label, className="crumb-label"),
            html.Span(
                value,
                className="crumb-value crumb-gold" if gold else "crumb-value",
            ),
        ],
        className="crumb",
    )


def _build_breadcrumbs(
    composition: str, nvac: int, temp: float, idx: int,
    energy_barrier: float, move_type: str, family_id: str,
    total: int,
) -> list:
    """Ordered list of crumb spans for the header breadcrumb strip."""
    return [
        _crumb("run",       f"{composition} / {nvac}vac / T{int(temp)}"),
        _crumb("event",     f"#{idx}"),
        _crumb("Ea",        f"{energy_barrier:.3f} eV"),
        _crumb("move_type", str(move_type), gold=True),
        _crumb("family",    str(family_id) or "—"),
        # TODO(later PR): wire actual filtered count once sidebar filter state
        # is surfaced via a store. For now only total is shown.
        html.Span(
            [
                html.Span("—", className="crumb-value crumb-gold"),
                html.Span(" / ", className="crumb-sep"),
                html.Span(f"{total:,}", className="crumb-value crumb-muted"),
                html.Span(" events", className="crumb-label"),
            ],
            className="crumb crumb-count",
        ),
    ]


def _breadcrumb_empty(message: str) -> list:
    """Placeholder breadcrumb content shown when no event is selected."""
    return [html.Span(message, className="crumb crumb-muted")]


