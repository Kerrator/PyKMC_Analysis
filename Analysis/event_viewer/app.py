# Event rail (PR5): prev/next stepper + info card + audited/unaudited chip.
# ---------------------------------------------------------------------------
@app.callback(
    Output("selected-event", "data", allow_duplicate=True),
    Output("event-dd", "value", allow_duplicate=True),
    Input("event-rail-prev", "n_clicks"),
    Input("event-rail-next", "n_clicks"),
    State("selected-event", "data"),
    prevent_initial_call=True,
)
def step_event(prev_clicks, next_clicks, selected):
    """Step one event forward or backward within the currently loaded run
    (sorted by idx_ref). Clamps at both ends."""
    from dash import callback_context
    trig = callback_context.triggered_id
    if trig not in ("event-rail-prev", "event-rail-next"):
        raise PreventUpdate
    if not selected:
        raise PreventUpdate
    sim = _resolve_sim(_sim_key(
        selected["composition"], selected["nvac"],
        float(selected["temp"]), selected["coloring"],
    ))
    if sim is None:
        raise PreventUpdate
    events = load_events(sim, CLASSIFICATIONS)
    if events.empty:
        raise PreventUpdate
    idx_refs = sorted(int(x) for x in events["idx_ref"].tolist())
    if not idx_refs:
        raise PreventUpdate
    current_idx = int(selected["idx_ref"])
    direction = -1 if trig == "event-rail-prev" else 1
    if current_idx in idx_refs:
        pos = idx_refs.index(current_idx)
        new_pos = max(0, min(len(idx_refs) - 1, pos + direction))
        new_idx = idx_refs[new_pos]
    else:
        new_idx = idx_refs[0]
    if new_idx == current_idx:
        raise PreventUpdate
    updated = dict(selected)
    updated["idx_ref"] = new_idx
    return updated, new_idx


