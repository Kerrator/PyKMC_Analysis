def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m Analysis.event_viewer.app",
        description="Browse and audit pyKMC events, either of one run (--run) "
                    "or of every run under a data root (--data-root, else "
                    "PYKMC_ANALYSIS_DATA_ROOT).",
    )
    source = parser.add_mutually_exclusive_group()
    source.add_argument(
        "--run", type=Path, default=os.environ.get("EVENT_VIEWER_RUN") or None,
        help="one run directory containing reference_table.pickle; the scatter "
             "then shows all of its events, classified or not",
    )
    source.add_argument(
        "--data-root", type=Path, metavar="PATH",
        help="directory of runs laid out as {composition}/{N}vac/T{temp}/{variant}/ "
             "(default: PYKMC_ANALYSIS_DATA_ROOT)",
    )
    parser.add_argument(
        "--composition",
        help="label for --run (default: from a {composition}/{N}vac/T{temp}/ "
             "parent layout, else the directory name)",
    )
    parser.add_argument("--nvac", type=int,
                        help="vacancy count for --run (default: layout, else 0)")
    parser.add_argument("--temp", type=int,
                        help="temperature in K for --run (default: layout, "
                             "else input.in [RateConstant] T, else 0)")
    parser.add_argument("--port", type=int,
                        default=int(os.environ.get("EVENT_VIEWER_PORT", "8050")),
                        help="HTTP port (default: EVENT_VIEWER_PORT, else 8050)")
    args = parser.parse_args(argv)
    if args.data_root is not None:
        # EVENT_VIEWER_RUN only fills the --run default; an explicit --data-root wins.
        args.run = None
        if not args.data_root.expanduser().is_dir():
            parser.error(f"--data-root {args.data_root} is not a directory")
    if args.run is not None and not (args.run.expanduser() / "reference_table.pickle").is_file():
        parser.error(f"--run {args.run} has no reference_table.pickle")
    return args


# Read the command line only when launched as a script; on import (Jupyter,
# tests) the host's argv is not ours, so only the environment variables apply.
ARGS = _parse_args(None if __name__ == "__main__" else [])


def _write_move_type_css() -> None:
    """Generate per-move-type / per-family hover CSS so the scatter checklist
    labels highlight in their matching scatter color when hovered.

    Dash serves any CSS placed under ``event_viewer/assets/`` automatically.
    """
    from pathlib import Path

    css_path = Path(__file__).parent / "assets" / "scatter_move_types.css"
    rules: list[str] = [
        "/* auto-generated by app.py — per-move-type + per-family hover colors */",
        "#scatter-type-checklist label, #scatter-family-checklist label, "
        "#scatter-direction-checklist label, #direction-overlay-checklist label {",
        "  padding: 2px 8px;",
        "  border-radius: 4px;",
        "  cursor: pointer;",
        "  transition: background 0.12s, color 0.12s;",
        "  margin-right: 6px !important;",
        "}",
    ]
    for move_type, color in CUSTOM_COLORS.items():
        rules.append(
            f'#scatter-type-checklist label:has(input[value="{move_type}"]):hover '
            f"{{ background: {color}22; color: {color}; "
            f"box-shadow: inset 0 0 0 1px {color}; }}"
        )
        rules.append(
            f'#scatter-type-checklist label:has(input[value="{move_type}"]:checked) '
            f"{{ border-bottom: 2px solid {color}; }}"
        )
    for fid, color in FAMILY_COLORS.items():
        rules.append(
            f'#scatter-family-checklist label:has(input[value="{fid}"]):hover '
            f"{{ background: {color}22; color: {color}; "
            f"box-shadow: inset 0 0 0 1px {color}; }}"
        )
        rules.append(
            f'#scatter-family-checklist label:has(input[value="{fid}"]:checked) '
            f"{{ border-bottom: 2px solid {color}; }}"
        )
    # Direction hover/checked styling — applies to both the scatter filter
    # checklist and the 3D overlay checklist (they use the same values).
    for did, color in DIRECTION_COLORS.items():
        for host in ("scatter-direction-checklist", "direction-overlay-checklist"):
            rules.append(
                f'#{host} label:has(input[value="{did}"]):hover '
                f"{{ background: {color}22; color: {color}; "
                f"box-shadow: inset 0 0 0 1px {color}; }}"
            )
            rules.append(
                f'#{host} label:has(input[value="{did}"]:checked) '
                f"{{ border-bottom: 2px solid {color}; }}"
            )
    css = "\n".join(rules) + "\n"
    try:
        if not css_path.exists() or css_path.read_text() != css:
            css_path.write_text(css)
    except OSError as exc:  # read-only install: serve the shipped file as is
        print(f"[event_viewer] could not refresh {css_path.name}: {exc}")


