def shutdown_server(armed):
    """Terminate the Python process when the user confirms via the clientside
    dialog. ``os._exit`` bypasses atexit hooks but is the only reliable way to
    kill a Flask/Werkzeug dev server from inside a request handler."""
    if not armed:
        return no_update
    import os
    import threading

    # Schedule the exit for a brief moment later so this callback can return
    # a status message to the browser before the process dies.
    threading.Timer(0.3, lambda: os._exit(0)).start()
    return "Shutting down…"


